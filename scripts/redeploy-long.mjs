// Replaces Calls, Pools and Prizes with the 30-day versions. Reputation stays (keeps everyone's score).
import fs from 'node:fs';
import { ethers } from 'ethers';
const art = n => JSON.parse(fs.readFileSync(new URL(`../artifacts/${n}.json`, import.meta.url), 'utf8'));
const file = new URL('../shared/addresses.json', import.meta.url);
const addrs = JSON.parse(fs.readFileSync(file, 'utf8'));
const keys = Object.fromEntries([...fs.readFileSync(process.env.WALLETS_FILE, 'utf8').matchAll(/\[(\w+)\]\s+ADDRESS=(\S+)\s+PRIVATE_KEY=(\S+)/g)].map(m => [m[1], m[3]]));
const provider = new ethers.JsonRpcProvider(process.env.RPC_URL);
const dep = new ethers.Wallet(keys.deployer, provider), owner = new ethers.Wallet(keys.owner, provider);
const t = async (l, p) => { const r = await (await p).wait(); if (r.status !== 1) throw new Error(l); console.log(' ', l); };
const oldCalls = new ethers.Contract(addrs.calls, art('Calls').abi, provider);
const oldPools = new ethers.Contract(addrs.pools, art('Pools').abi, provider);
const gate = await oldCalls.gate(), callsSettler = await oldCalls.settler(), poolsSettler = await oldPools.settler();
const maxStake = await oldCalls.maxStake(), maxEntry = await oldPools.maxEntry();
const before = await provider.getBalance(dep.address);
const make = async (n, ...a) => { const c = await new ethers.ContractFactory(art(n).abi, art(n).bytecode, dep).deploy(...a); await c.deploymentTransaction().wait(); console.log(n, await c.getAddress()); return c; };
const calls = await make('Calls', addrs.reputation, gate, maxStake);
const pools = await make('Pools', addrs.reputation, maxEntry);
const prizes = await make('Prizes', await calls.getAddress());
await t('calls settler', calls.setSettler(callsSettler));
await t('pools settler', pools.setSettler(poolsSettler));
for (const [id, feed] of Object.entries(addrs.priceFeeds)) await t('asset ' + id, pools.setAsset(Number(id), true, feed, Number(await oldPools.assetMaxAge(Number(id)))));
await t('open questions (slot 7)', pools.setAsset(7, true, ethers.ZeroAddress, 3600));
await t('calls ownership offered', calls.transferOwnership(owner.address));
await t('pools ownership offered', pools.transferOwnership(owner.address));
await t('calls ownership accepted', calls.connect(owner).acceptOwnership());
await t('pools ownership accepted', pools.connect(owner).acceptOwnership());
const rep = new ethers.Contract(addrs.reputation, art('Reputation').abi, owner);
await t('reputation writer: calls on', rep.setWriter(await calls.getAddress(), true));
await t('reputation writer: pools on', rep.setWriter(await pools.getAddress(), true));
await t('reputation writer: old calls off', rep.setWriter(addrs.calls, false));
await t('reputation writer: old pools off', rep.setWriter(addrs.pools, false));
addrs.callsOld = addrs.calls; addrs.poolsOld = addrs.pools; addrs.prizesOld = addrs.prizes;
addrs.calls = await calls.getAddress(); addrs.pools = await pools.getAddress(); addrs.prizes = await prizes.getAddress();
fs.writeFileSync(file, JSON.stringify(addrs, null, 2) + '\n');
console.log('owners ok:', (await calls.owner()) === owner.address, (await pools.owner()) === owner.address, 'maxStake', ethers.formatEther(await calls.maxStake()), 'maxEntry', ethers.formatEther(await pools.maxEntry()), 'cost MON', ethers.formatEther(before - await provider.getBalance(dep.address)));
